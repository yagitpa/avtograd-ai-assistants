def sticky(name: str, content: str, x: int, y: int, w: int, h: int, color: int) -> dict:
    return {
        "parameters": {"content": content, "height": h, "width": w, "color": color},
        "id": f"note-{name}", "name": name, "type": STICKY,
        "typeVersion": 1, "position": [x, y],
    }


def block_text(title: str, lead: str, bullets: list[str]) -> str:
    lines = [f"## {title}", "", lead, ""]
    lines += [f"- {b}" for b in bullets]
    return "\n".join(lines)


def annotate(doc: dict) -> dict:
    """Раскладывает узлы по шагу и обкладывает их записками."""
    spec = DOCS.get(doc["name"])
    if not spec:
        return doc

    doc["nodes"] = [n for n in doc["nodes"] if n["type"] != STICKY]
    order = {n["name"]: i for i, n in enumerate(doc["nodes"])}
    for node in doc["nodes"]:
        node["position"] = [order[node["name"]] * STEP, NODE_Y]

    # Рамка блока считается от позиций узлов, которые в него входят, а не
    # накоплением ширин: иначе вторая записка уезжает правее своего первого
    # узла, и на холсте блок охватывает не то, о чём рассказывает.
    notes: list[dict] = []
    right = 0
    for idx, (title, members, lead, bullets) in enumerate(spec["блоки"], start=1):
        columns = [order[m] * STEP for m in members if m in order]
        if not columns:
            continue
        left = min(columns) - PAD
        width = max(columns) - min(columns) + STEP + PAD
        notes.append(sticky(f"Блок {idx}", block_text(title, lead, bullets),
                            left, BLOCK_Y, width, BLOCK_H, BLUE))
        right = max(right, left + width)

    warn = "## ⚠️ На что обратить внимание\n\n" + "\n".join(f"- {g}" for g in spec["грабли"])
    notes.append(sticky("Грабли", warn, right + PAD, BLOCK_Y, 420, BLOCK_H, RED))
    cursor = right + PAD + 420

    head = (f"# {doc['name']}\n\n## 🎯 Цель и задачи сценария\n\n{spec['цель']}")
    notes.insert(0, sticky("Цель", head, -2 * PAD, BLOCK_Y - 300,
                           cursor + 3 * PAD, BLOCK_H + 340, GREY))

    doc["nodes"] = notes + doc["nodes"]
    return doc


def main() -> int:
    for path in sorted(WORKFLOWS.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        before = sum(1 for n in doc["nodes"] if n["type"] == STICKY)
        doc = annotate(doc)
        after = sum(1 for n in doc["nodes"] if n["type"] == STICKY)
        path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
        state = "нет описания в DOCS" if not after else f"записок {after} (было {before})"
        print(f"  · {doc['name']}: {state}")
    print("\nЗаписки переписаны заново. Отправить в n8n: python tools/n8n_push.py push")
    return 0


if __name__ == "__main__":
    sys.exit(main())
