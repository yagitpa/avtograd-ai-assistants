"""Тесты ядра: валидатор стоп-листа, проверки идентификаторов, подстановки.

Здесь заперты все дефекты, найденные прогонами и живыми тестами. Каждый из
них однажды уже прошёл к клиенту, и у каждого есть общая черта: ошибался не
ассистент, а код вокруг него — шаблон ловил подстроку внутри слова, число с
пробелом между разрядами не считалось числом, служебный код уезжал в ответ.

Ни сети, ни вызовов модели: тесты выполняются за секунду.

Запуск:  python tests/test_core.py
Код возврата 1 — есть падения.
"""

from __future__ import annotations

import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from assistant import (active_promotions, expand_days, guess_mode,  # noqa: E402
                       humanize_ids, looks_like_vehicle_id, phone_note, plate_note,
                       split_mode, validate_outgoing, working_hours)

for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass

passed, failed = 0, []


def check(condition: bool, title: str) -> None:
    global passed
    if condition:
        passed += 1
    else:
        failed.append(title)


def test_red_lines() -> None:
    """Красные линии должны срабатывать — это условие приёмки, а не пожелание."""
    cases = [
        ("Это гарантийный случай, признаём", "решение по гарантии"),
        ("Передаю запрос на скидку 200 000 ₽ руководителю", "сумма скидки"),
        ("Дадим за вашу машину 900 000 рублей", "сумма выкупа"),
        ("Банк одобрит вам кредит", "обещание банка"),
        ("Компенсируем вам простой", "компенсация"),
        ("Это подшипник ступицы", "диагноз"),
        ("Пришлите скан паспорта", "запрос документов"),
        ("Гарантирую, что успеем", "абсолютное обещание"),
        ("Я передал обращение менеджеру", "ложное действие"),
        ("Записал вас на четверг", "ложное действие"),
        ("Соединю вас с менеджером", "ложное действие"),
        ("Передам ответственному emp-08", "служебный идентификатор"),
        ("Поставлю в дежурную очередь on_call.quality", "служебный идентификатор"),
        ("Итоговая цена — два миллиона", "итоговая цена"),
        ("Будет готово к пятнице", "обещание срока"),
    ]
    for text, kind in cases:
        check(kind in validate_outgoing(text), f"стоп-лист ловит: {text}")


def test_false_positives() -> None:
    """Ложное срабатывание — такой же дефект, как пропуск (stop-list.md)."""
    clean = [
        # Рекомендованные замены из самого стоп-листа.
        ("Признать случай гарантийным может только руководитель сервиса", "отрицание по гарантии"),
        ("Решение принимает банк — я не гарантирую одобрение", "отрицание обещания"),
        # Подстрока внутри слова: «процент» содержит «оцен», «подобрать» — «одобр».
        ("Оклад 60 000 ₽ плюс процент, совокупно 110 000–180 000 ₽", "процент не оценка выкупа"),
        ("Подобрать вам автомобиль могу сам", "подобрать не одобрение"),
        # Прошедшее время в придаточном описывает будущее.
        ("Хотите, чтобы я передал запрос рекрутеру?", "предложение, а не отчёт"),
        # Число с пробелом между разрядами против года выпуска.
        ("Aurora X5 2024 года, пробег 41 200 км", "модель и год — не сумма"),
        ("Цена по стоку 2 490 000 ₽, информация не является публичной офертой", "цена из стока"),
        ("Наряд wo-1012 в работе", "номер наряда клиент видит в ДЦ"),
        # Единица измерения после числа означает, что это не деньги.
        ("Передаю запрос о сумме выкупа Vector Sedan 2019 (60 000 км) руководителю",
         "пробег в скобках — не названная сумма"),
        ("Пробег 41 200 км, ближайшее ТО-3 при 45 000 км", "километры не рубли"),
        # «карт» без уточнения ловило карточку автомобиля — ровно ту фразу,
        # которой ассистент отвечает на непонятный идентификатор.
        ("Пришлите VIN, и я подниму карточку автомобиля", "карточка машины не банковская карта"),
    ]
    for text, title in clean:
        check(not validate_outgoing(text), f"валидатор не трогает корректное: {title}")

    # Придаточное с «чтобы» снимает запрет только с себя, а не со всей реплики.
    check("ложное действие" in validate_outgoing(
        "Хотите, чтобы я уточнил? Я уже записал вас на четверг."),
        "отчёт о сделанном после придаточного всё равно ловится")


def test_identifiers() -> None:
    check(plate_note("госномер П 001 ЩЮ 222 rus"), "буквы П, Щ, Ю в номерах не бывают")
    check(plate_note("Ъ777ЫЫ99"), "номер без пробелов тоже проверяется")
    check(plate_note("номер А001АА777") is None, "настоящий номер замечаний не вызывает")
    check(plate_note("мой номер В 123 УК 45") is None, "номер с пробелами разбирается")
    check(plate_note("Aurora X5 2024 года") is None, "модель с годом за номер не принимается")

    check(phone_note("мой телефон +38 222 222 22"), "номер из десяти цифр с кодом страны неполон")
    check(phone_note("телефон 916 123 45 67") is None, "десять цифр без кода — норма")
    check(phone_note("позвоните 8 916 123 45 67") is None, "одиннадцать цифр — норма")
    check(phone_note("бюджет 2 500 000 рублей") is None, "бюджет не телефон")
    check(phone_note("сегодня 2026-09-18") is None, "дата не телефон")

    check(looks_like_vehicle_id("VIN TESTAG00000000901"), "VIN распознаётся")
    check(looks_like_vehicle_id("номер А001АА777"), "госномер распознаётся")
    check(not looks_like_vehicle_id("когда пройти ТО"), "обычный вопрос не идентификатор")


def test_service_codes() -> None:
    """Служебный код не должен доезжать до модели: подменяется при сборке знаний."""
    text = humanize_ids("escalate_to: emp-01; не сочетается с ACT-109; дежурство on_call.quality")
    check("emp-01" not in text, "идентификатор сотрудника подменён")
    check("Тимофеева" in text, "подставлено имя ответственного")
    check("ACT-109" not in text, "код акции подменён названием")
    check("on_call.quality" not in text, "ключ дежурства подменён")


def test_schedule_and_promotions() -> None:
    check(expand_days("mon-sun") == {"mon", "tue", "wed", "thu", "fri", "sat", "sun"},
          "диапазон дней разворачивается")
    check(expand_days("sat") == {"sat"}, "одиночный день остаётся собой")
    # Регресс: «thu» in «mon-sun» было False, и любой будний день читался как выходной.
    hours, is_open = working_hours("sales_new", datetime(2026, 9, 17, 19, 25))
    check(is_open, "среда вечером — рабочее время отдела продаж")
    hours, is_open = working_hours("sales_new", datetime(2026, 9, 17, 23, 40))
    check(not is_open, "ночью отдел закрыт")

    names = [a["name"] for a in active_promotions("2026-09-18")]
    check("Трейд-ин Осень" in names, "действующая акция предлагается")
    check("Летний сервисный пакет" not in names, "истёкшая акция не предлагается")
    check(not active_promotions("2027-01-01"), "через год не действует ни одна акция")


def test_mode_contract() -> None:
    """Режим, выбранный ассистентом, обязан доходить до кода и не доходить до клиента.

    Регресс живой проверки 19 сентября: ассистент писал клиенту «передаю
    менеджеру по качеству», ядро помечало ответ как ОТВЕТ, дежурному не
    приходило ничего. Обещание без адресата хуже отсутствия эскалации.
    """
    text, mode = split_mode("Передаю обращение руководителю сервиса.\n#РЕЖИМ: ЭСКАЛАЦИЯ")
    check(mode == "ЭСКАЛАЦИЯ", "объявленный режим прочитан")
    check("РЕЖИМ" not in text, "служебная строка снята перед отправкой клиенту")
    check(text.endswith("сервиса."), "текст ответа не пострадал")

    _, mode = split_mode("Записал вас на 21 сентября.\nРЕЖИМ: ОТВЕТ")
    check(mode == "ОТВЕТ", "строка читается и без решётки")

    text, mode = split_mode("Уточните VIN, пожалуйста.")
    check(mode is None, "молчание о режиме не выдумывается за ассистента")
    check(text == "Уточните VIN, пожалуйста.", "текст без строки режима не тронут")

    # Страховка на случай, когда контракт нарушен: сработавшая запись карты
    # эскалаций плюс формулировка передачи.
    check(guess_mode("Передаю обращение руководителю сервиса.", ["ESC-003"]) == "ЭСКАЛАЦИЯ",
          "эскалация угадана по записи и формулировке")
    check(guess_mode("Стоимость ТО-2 — 18 900 рублей.", []) == "ОТВЕТ",
          "обычный ответ не превращается в эскалацию")


def main() -> int:
    for test in (test_red_lines, test_false_positives, test_identifiers,
                 test_service_codes, test_schedule_and_promotions,
                 test_mode_contract):
        test()
    print(f"Проверок выполнено: {passed + len(failed)}")
    if failed:
        print(f"\nПадений: {len(failed)}")
        for title in failed:
            print(f"  · {title}")
        return 1
    print("Падений нет. Красные линии держатся, корректные ответы проходят.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
